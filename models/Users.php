    /**
     * sqlashdan oldingi methodlar
     * @param bool $insert
     * @return bool
     */
    public function beforeSave($insert)
    {

        if ($this->isNewRecord)
        {
            $this->registry_date = date("Y-m-d H:i");
            $this->status = self::STATUS_ACTIVE;
            // $this->permission = self::WORKER;
            $user = Yii::$app->user->identity;
            $this->password = Yii::$app->security->generatePasswordHash($this->password);
            // $this->username = self::Unikal();
            $this->access_token = Yii::$app->getSecurity()->generateRandomString();
        }

        $this->phone = str_replace("-","",$this->phone);
        if($this->new_password != null) $this->password = Yii::$app->security->generatePasswordHash($this->new_password);
        return parent::beforeSave($insert); // TODO: Change the autogenerated stub
    }

    /**
     * unikalni usrname berish
     * @return string
     * @throws \yii\db\Exception
     */
    public static function Unikal(){
        do{
            $rand = "u".random_int(1000000000,9999999999);
            $base = Yii::$app->db->createCommand("SELECT * FROM users WHERE username='".$rand."'")->queryOne();
        }while($base != false);
        return $rand;
    }


