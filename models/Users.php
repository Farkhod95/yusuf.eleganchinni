    /**
     * user rasmini urlni olish
     * @return string
     */
    public function getAvatar()
    {
        if ($this->avatar == ''){
            return '/web/img/nouser.png';
        }else{
            return Yii::$app->params['siteName']   . "/web/uploads/" . self::DIR_IMAGE . "/" . $this->avatar;
        }
    }


    /**
     * userga rasm yuklash
     * @throws \yii\db\Exception
     */
    public function upload()
    {
        $fileName = $this->id . '-' . Yii::$app->security->generateRandomString() . '.' . $this->image->extension;
        if(!empty($this->image))
        {
            if(file_exists('uploads/avatars/'.$this->avatar) && $this->avatar != null)
            {
                unlink('uploads/avatars/'.$this->avatar);
            }

            $this->image->saveAs('uploads/avatars/'.$fileName);
            Yii::$app->db->createCommand()->update('users', ['avatar' => $fileName], [ 'id' => $this->id ])->execute();
        }
    }

    public static function isAdminRight($id)
    {
        return self::findOne($id)->permission == 1;
    }

    public static function isMenejerRight($id)
    {
        return self::findOne($id)->permission == 1 or self::findOne($id)->permission == 2 or self::findOne($id)->permission == 5 or self::findOne($id)->permission == 6 or self::findOne($id)->permission == 7;
    }

    public static function isWorkerRight($id)
